function soma(n1=0, n2=0){
    return n1 + n2
}

console.log(soma(7))

// criado uma função chamada 'soma' que recebe dois parâmetros, 'n1' e 'n2', ambos com um valor padrão de 0. A função retorna a soma dos dois parâmetros. Em seguida, a função é chamada com apenas um argumento (7), o que significa que o segundo parâmetro usará seu valor padrão de 0. O resultado da soma (7 + 0) é então impresso no console. Ou posso entrar com os dois números, por exemplo: console.log(soma(7, 3)) e o resultado seria 10.